import assert from 'node:assert/strict';
import {buildStore, type SelectedPart} from '../src/store/build-store';
const cpu = (id:string,price:number):SelectedPart => ({id,name:id,brand:'AMD',price,discountRate:10,image:null,categoryCode:'CPU',attributes:{socket:'AM5',cores:8,threads:16,boostClockGHz:5.2,tdpWatts:120} as SelectedPart['attributes']});
const first=cpu('cpu-a',100000),second=cpu('cpu-b',200000);
buildStore.getState().clearAll();
buildStore.getState().selectPart(first);
buildStore.getState().selectPart(second);
assert.equal(Object.keys(buildStore.getState().selectedParts).length,2);
assert.equal(buildStore.getState().totalPrice,300000);
assert.equal(buildStore.getState().totalDiscountedPrice,270000);
assert(buildStore.getState().compatibility.issues.some(i=>i.ruleId==='multiple-parts-review'));
buildStore.getState().selectPart(first);
assert.equal(Object.keys(buildStore.getState().selectedParts).length,2);
buildStore.getState().removePart(first.id);
assert.deepEqual(Object.keys(buildStore.getState().selectedParts),[second.id]);
assert.equal(buildStore.getState().totalPrice,200000);
const merge=buildStore.persist.getOptions().merge!;
const restored=merge({selectedParts:{CPU:first}},buildStore.getState());
assert.deepEqual(Object.keys(restored.selectedParts),[first.id]);
assert.equal(restored.totalPrice,100000);
const multiple=merge({selectedParts:{[first.id]:first,[second.id]:second}},buildStore.getState());
assert.equal(Object.keys(multiple.selectedParts).length,2);
assert.equal(multiple.totalPrice,300000);
buildStore.getState().loadPrebuilt([first,second]);
assert.equal(Object.keys(buildStore.getState().selectedParts).length,2);
buildStore.getState().clearAll();
assert.equal(buildStore.getState().totalPrice,0);
console.log('PASS: same-category additions, deduplication, per-item removal, totals, compatibility notice, legacy/new persistence, prebuilt loading, clear');
